    /// Строки вида `kind` — замыкание ребер `edges` по потомкам (снятие права снимает потомков, backend FUN_180eebfb0).
    fn check(kind: &str, edges: &[(usize, usize)]) {
        let (_, names, deps, _) = super::KINDS.iter().find(|k| k.0 == kind).unwrap();
        for f in 0..names.len() {
            let (mut seen, mut stack) = (vec![false; names.len()], vec![f]);
            while let Some(x) = stack.pop() {
                for &(_, c) in edges.iter().filter(|e| e.0 == x) {
                    if !seen[c] {
                        seen[c] = true;
                        stack.push(c);
                    }
                }
            }
            let row: String = (0..names.len()).map(|r| if r == f { '=' } else if seen[r] { '+' } else { '-' }).collect();
            assert_eq!(deps[f], row, "{kind}.{}", names[f]);
        }
    }

